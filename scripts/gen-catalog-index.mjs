import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const { items } = JSON.parse(fs.readFileSync(new URL('data/public-catalog.json', root), 'utf8'));
const keys = new Set(items.map(item => item.kind + ':' + item.id));
if (keys.size !== items.length || items.some(item => item.visibility !== 'public')) throw new Error('Invalid public catalog');
const finder = fs.readFileSync(new URL('js/find-addon.js', root), 'utf8');
for (const match of finder.matchAll(/addons: (\[[^\]]+\])/g)) {
  for (const key of JSON.parse(match[1])) if (!keys.has(key)) throw new Error('Finder points to missing public add-on: ' + key);
}
const output = '// Generated by scripts/gen-catalog-index.mjs.\nexport const CATALOG_INDEX = ' +
  JSON.stringify(items.map(item => ({ key: item.kind + ':' + item.id, name: item.name })), null, 2) + ';\n';
const target = new URL('js/catalog-index.js', root);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node scripts/gen-catalog-index.mjs');
} else fs.writeFileSync(target, output);
console.log('Catalog index: ' + items.length + ' public entries; every finder destination exists.');
