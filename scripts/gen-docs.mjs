/* What the search box reads: titles, headings and words, for every page. */
function searchIndex(base) {
  const entries = [];
  for (const g of base.guides) {
    const heads = g.body.filter((b) => b.type === "heading").map((b) => b.text);
    const text = g.body.map((b) => [b.text, ...(b.items || []).map((i) => (typeof i === "string" ? i : [i.text, i.note].join(" ")))].filter(Boolean).join(" ")).join(" ");
    entries.push({ k: "Guide", t: g.title, u: `guides/${g.id}/`, s: plainText(g.summary), h: heads.join(" | "), x: plainText(text).slice(0, 2400) });
  }
  for (const f of base.published) {
    entries.push({ k: AREA[f.area].label, t: f.name, u: `features/${f.area}/#${f.id}`, s: f.summary, h: "", x: [f.where, ...(f.how || []), f.phone, ...(f.limits || [])].filter(Boolean).join(" ") });
  }
  for (const r of base.releases) {
    entries.push({ k: "What’s new", t: `Archie ${r.version}`, u: `whats-new/#${r.id}`, s: r.date, h: "", x: r.items.map((i) => i.text).join(" ").slice(0, 2400) });
  }
  return JSON.stringify({ entries }) + "\n";
}

/* ---------- run ---------- */

function build() {
  const C = chrome();
  const guides = readGuides();
  const all = readFeatures(guides);
  const published = all.filter((f) => f.claimable);
  const areas = AREAS.map((a) => ({ ...a, count: published.filter((f) => f.area === a.id).length })).filter((a) => a.count);
  const releases = readReleases();
  const base = { guides, published, areas, releases, featureCount: published.length };
  const files = new Map();
  files.set("index.html", homePage(C, base));
  guides.forEach((g, i) => files.set(`guides/${g.id}/index.html`, guidePage(g, i, C, base)));
  if (areas.length) {
    files.set("features/index.html", allFeaturesPage(C, base));
    for (const a of areas) files.set(`features/${a.id}/index.html`, areaPage(a, C, base));
  }
  if (releases.length) files.set("whats-new/index.html", whatsNewPage(C, base));
  files.set("search.json", searchIndex(base));
  return { files, all, published };
}

function onDisk(dir = OUT, rel = "") {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? onDisk(path.join(dir, e.name), rel + e.name + "/") : [rel + e.name]);
}

function report(all) {
  const out = [];
  for (const a of AREAS) {
    const mine = all.filter((f) => f.area === a.id);
    if (!mine.length) continue;
    out.push(`\n${a.label} (${mine.filter((f) => f.claimable).length} published, ${mine.filter((f) => !f.claimable).length} held)`);
    for (const f of mine) {
      const flags = [f.released || "no release", f.editions !== "both" ? f.editions : "", f.phone ? "phone" : "", f.unwatched ? "never watched" : ""].filter(Boolean).join(", ");
      out.push(`  ${f.claimable ? "  " : "H "}${f.name} [${flags}]${f.claimable ? "" : `\n      held: ${f.hold || "no reason given"}`}`);
    }
  }
  const held = all.filter((f) => !f.claimable).length;
  out.push(`\n${all.length} features: ${all.length - held} published, ${held} held (H).`);
  console.log(out.join("\n"));
}

const { files, all } = build();
if (process.argv.includes("--report")) {
  report(all);
} else if (process.argv.includes("--check")) {
  const stale = [];
  for (const [rel, html] of files) {
    const p = path.join(OUT, rel);
    const have = fs.existsSync(p) ? fs.readFileSync(p, "utf8").replace(CSP_RE, "") : null;
    if (have !== html.replace(CSP_RE, "")) stale.push(rel);
  }
  for (const rel of onDisk()) if (!files.has(rel)) stale.push(rel + " (nothing generates it)");
  if (stale.length) {
    console.error("gen-docs: out of date. Run node scripts/gen-docs.mjs, then python3 scripts/gen-csp.py.\n  " + stale.join("\n  "));
    process.exit(1);
  }
  console.log(`gen-docs: clean. ${files.size} files.`);
} else {
  for (const rel of onDisk()) if (!files.has(rel)) fs.rmSync(path.join(OUT, rel));
  for (const [rel, html] of files) {
    const p = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    // Keep the CSP gen-csp.py wrote, so a rerun with nothing changed changes nothing.
    const old = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "";
    const csp = old.match(CSP_RE);
    fs.writeFileSync(p, csp ? html.replace(CSP_RE, csp[0]) : html);
  }
  // Folders a retired page leaves behind.
  for (const d of ["guides", "features"]) {
    const dir = path.join(OUT, d);
    if (!fs.existsSync(dir)) continue;
    for (const e of fs.readdirSync(dir)) {
      const p = path.join(dir, e);
      if (fs.statSync(p).isDirectory() && !fs.readdirSync(p).length) fs.rmdirSync(p);
    }
  }
  console.log(`gen-docs: wrote ${files.size} files.`);
}
