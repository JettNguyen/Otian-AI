/* ---------- inline text ---------- */

const link = (href, label) => `<a href="${attr(href)}">${label}</a>`;

/* A guide that names another ("The Claim your agent guide covers this", "the guide called Where
   your information goes") gets a link to it. Only those two forms, because a bare title such as
   Memory or Knowledge is also an ordinary word. */
function crossLink(html, ctx) {
  for (const g of ctx.guides) {
    if (g.id === ctx.here) continue;
    const t = reEsc(esc(g.title));
    const href = `${ctx.D}guides/${g.id}/`;
    html = html.replace(new RegExp(`(guide called )(${t})(?=[\\s.,;:)]|$)`, "gi"), (m, a, b) => `${a}${link(href, b)}`);
    html = html.replace(new RegExp(`(\\b[Tt]he )(${t})( guide\\b)`, "gi"), (m, a, b, c) => `${a}${link(href, b)}${c}`);
  }
  return html;
}

/* Archie's `Linkified` (src/app/shared.tsx), on the web: a named link, then bare addresses, with
   trailing punctuation left outside the link. */
function inline(raw, ctx) {
  const parts = fill(raw).split(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g);
  let out = "";
  for (let i = 0; i < parts.length; i++) {
    if (i % 3 === 1) { out += link(parts[i + 1], esc(parts[i])); i++; continue; }
    out += parts[i].split(/(https?:\/\/[^\s]+)/g).map((p, j) => {
      if (j % 2 === 0) return ctx ? crossLink(esc(p), ctx) : esc(p);
      const trailing = /[.,;:!?)”’"']+$/.exec(p)?.[0] ?? "";
      const href = trailing ? p.slice(0, -trailing.length) : p;
      return link(href, esc(href)) + esc(trailing);
    }).join("");
  }
  return out;
}

