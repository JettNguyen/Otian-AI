/* ---------- guides ---------- */

function readGuides() {
  const raw = JSON.parse(fs.readFileSync(GUIDES, "utf8")).guides;
  const known = new Set(["heading", "text", "list", "steps", "note", "table", "setup_steps"]);
  for (const g of raw) {
    for (const k of ["id", "title", "summary", "body"]) if (!g[k]) throw new Error(`guide ${g.id || "?"} has no ${k}`);
    for (const b of g.body) if (!known.has(b.type)) throw new Error(`guide ${g.id}: unknown block ${b.type}`);
    g.section = SECTIONS.some((s) => s.id === g.section) ? g.section : "good_to_know";
    g.part = Number(g.part) || 0;
  }
  // Archie's order: by section, then the guides their section leans on, then by title, a series
  // sorting together under its first part's title.
  const first = new Map();
  for (const g of raw) if (g.series && (!first.has(g.series) || g.part < first.get(g.series).part)) first.set(g.series, g);
  const sortTitle = (g) => (g.series && first.get(g.series)?.title) || g.title;
  const leads = (g) => LEADS.has(g.id) || Boolean(g.series && LEADS.has(first.get(g.series)?.id));
  const out = [];
  for (const s of SECTIONS) {
    out.push(...raw.filter((g) => g.section === s.id).sort((a, b) =>
      Number(leads(b)) - Number(leads(a)) || sortTitle(a).localeCompare(sortTitle(b)) || a.part - b.part));
  }
  for (const g of out) {
    g.parts = g.series ? out.filter((o) => o.series === g.series).length : 0;
    g.next = g.series ? out.find((o) => o.series === g.series && o.part === g.part + 1) : undefined;
  }
  return out;
}

function cell(c, first, ctx) {
  // Firestore keeps a table row as { cells: [...] }; the repo's JSON keeps it as an array.
  if (c === "✓") return `<td class="dx-yes"><span aria-hidden="true">✓</span><span class="sr-only">yes</span></td>`;
  if (c === "✕") return `<td class="dx-no"><span aria-hidden="true">✕</span><span class="sr-only">no</span></td>`;
  return first ? `<th scope="row">${inline(c, ctx)}</th>` : `<td>${inline(c, ctx)}</td>`;
}

function block(b, ctx, ids) {
  switch (b.type) {
    case "heading": {
      let id = slug(b.text) || "section";
      while (ids.has(id)) id += "-2";
      ids.add(id);
      ctx.toc.push({ id, text: b.text });
      return `<h2 id="${id}">${esc(b.text)}<a class="dx-hash" href="#${id}" aria-label="Link to ${attr(b.text)}">#</a></h2>`;
    }
    case "text":
      return `<p>${inline(b.text, ctx)}</p>`;
    case "list":
      return `<ul>${b.items.map((i) => `<li>${inline(i, ctx)}</li>`).join("")}</ul>`;
    case "steps":
      return `<ol class="dx-steps">${b.items.map((i) => `<li>${inline(i, ctx)}</li>`).join("")}</ol>`;
    case "note":
      return `<aside class="dx-note" aria-label="Note"><p>${inline(b.text, ctx)}</p></aside>`;
    case "table": {
      const rows = b.rows.map((r) => (Array.isArray(r) ? r : r.cells));
      return `<div class="dx-table"><table>
            <thead><tr>${b.columns.map((c, i) => `<th scope="col"${i ? "" : ' class="dx-l"'}>${esc(c)}</th>`).join("")}</tr></thead>
            <tbody>${rows.map((r) => `<tr>${r.map((c, i) => cell(c, i === 0, ctx)).join("")}</tr>`).join("")}</tbody>
          </table></div>`;
    }
    case "setup_steps":
      // `shot` names a picture Archie may not have yet; a missing one renders nothing in Archie,
      // and nothing here, so every step already reads on its own.
      return `<ol class="dx-steps dx-setup">${b.items.map((s) => `<li>
            <p>${inline(s.text, ctx)}</p>${s.copy ? `
            <p class="dx-copy"><code>${esc(fill(s.copy))}</code><button type="button" class="dx-copy-b" data-copy="${attr(fill(s.copy))}">Copy</button></p>` : ""}${s.note ? `
            <p class="dx-aside">${inline(s.note, ctx)}</p>` : ""}
          </li>`).join("")}</ol>`;
  }
  return "";
}

/* ---------- features ---------- */

function readFeatures(guides) {
  if (!fs.existsSync(FEATURES)) return [];
  const all = JSON.parse(fs.readFileSync(FEATURES, "utf8")).features;
  const trust = new Set(fs.readFileSync(TRUST, "utf8").split("\n").filter((l) => l.startsWith("### ")).map((l) => l.slice(4).trim()));
  const ids = new Set();
  const bad = [];
  for (const f of all) {
    const where = `feature ${f.id || "?"}`;
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(f.id || "")) bad.push(`${where}: id must be kebab-case`);
    if (ids.has(f.id)) bad.push(`${where}: listed twice`);
    ids.add(f.id);
    if (!AREA[f.area]) bad.push(`${where}: no area called ${f.area}`);
    for (const k of ["name", "summary"]) if (!f[k]) bad.push(`${where}: no ${k}`);
    if (!["both", "teams", "individual"].includes(f.editions)) bad.push(`${where}: editions is both, teams or individual`);
    if (f.claimable && !f.released) bad.push(`${where}: claimable but in no release`);
    if (f.claimable && !(f.trust || []).length) bad.push(`${where}: claimable with no TRUST.md heading`);
    for (const h of f.trust || []) if (!trust.has(h.trim())) bad.push(`${where}: TRUST.md has no heading "${h.slice(0, 80)}"`);
    if (f.guide && !guides.some((g) => g.id === f.guide)) bad.push(`${where}: no guide called ${f.guide}`);
    // `trust` and `wording` quote TRUST.md as it stands, dashes and all, and are never printed.
    const { trust: t, wording: w, ...shown } = f;
    if (/[\u2014\u2013]/.test(JSON.stringify(shown))) bad.push(`${where}: has a dash the site does not print`);
  }
  if (bad.length) throw new Error("data/docs-features.json:\n  " + bad.join("\n  "));
  return all;
}

