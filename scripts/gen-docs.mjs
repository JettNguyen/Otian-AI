function toc(items) {
  if (items.length < 2) return { aside: "", inline: "" };
  const list = items.map((t) => `<li><a href="#${t.id}">${esc(t.text)}</a></li>`).join("");
  return {
    aside: `<nav class="dx-toc" aria-label="On this page"><p>On this page</p><ul>${list}</ul></nav>`,
    inline: `<details class="dx-toc-m"><summary>On this page</summary><ul>${list}</ul></details>`,
  };
}

function frame(C, ctx, { title, desc, main, tocAside = "", wide = false }) {
  const P = ctx.P;
  const head = rebase(C.head, P)
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>`)
    .replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${attr(desc)}" />`);
  return `${head}${style(P)}</head>
${rebase(C.top, P)}  <main id="main" class="dx">
    ${BANNER}
    <div class="dx-wrap${wide || !tocAside ? " dx-wide" : ""}">
      <article class="dx-main">
${main}
      </article>
      ${tocAside}
      ${sideNav(ctx)}
    </div>
  </main>
${rebase(C.tail, P)}`;
}

