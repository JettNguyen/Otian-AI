/* Write Archie Docs into docs/: the guides, every feature by area, and what is new in each release.
 *
 * WHERE THE WORDS COME FROM. Three sources, and none of them is written here:
 *
 *   - The guides are the ones Archie shows on its Resources page, word for word, from
 *     data/public-guides.json (scripts/sync-public-catalog.mjs snapshots the public catalog). The
 *     catalog's copy is the one installed apps show, because it wins over the copy built into the
 *     app, so the docs say what the app says on the same day. A guide is fixed in the Archie repo
 *     (data/marketplace/resources/), pushed, and snapshotted here; never edited in docs/.
 *   - The features are data/docs-features.json. Each one names the TRUST.md headings it rests on,
 *     and this refuses to write anything while a heading is missing, because a claim that is not in
 *     TRUST.md may not be made on this site. Only `claimable` features are published. The rest are
 *     held, with the reason, and `--report` lists them, so the file is the whole inventory and the
 *     pages are the part of it we may say.
 *   - What's new is archie/releases.json, the notes every update already shows, from FIRST_RELEASE
 *     on. Older notes use names and prices the site no longer prints.
 *
 * THE CHROME. The head, the three copies of the menu and the footer are copied from a live page at
 * generation time, as scripts/gen-library.mjs does, so a menu sweep can never leave these pages
 * behind. Docs pages sit at three depths, so the chrome's ../../ is rewritten for each. The CSP tag is
 * the one thing gen-csp.py writes afterwards, so --check ignores it.
 *
 * Usage:
 *   node scripts/gen-docs.mjs            write docs/, removing pages nothing generates any more
 *   node scripts/gen-docs.mjs --check    exit 1 if any page is out of date
 *   node scripts/gen-docs.mjs --report   print every feature, published or held, by area
 */

