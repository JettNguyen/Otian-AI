/* ---------- release notes ---------- */

const vnum = (v) => v.split(".").map(Number);
const vcmp = (a, b) => { const x = vnum(a), y = vnum(b); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };

/* The notes are a short list: "- " starts an item, an indented line continues it, and the only
   markup is **bold**, `code` and a named link. */
function notes(md) {
  const items = [];
  for (const line of md.split("\n")) {
    if (line.startsWith("- ")) items.push(line.slice(2).trim());
    else if (line.trim() && items.length) items[items.length - 1] += " " + line.trim();
    else if (line.trim()) items.push(line.trim());
  }
  const md1 = (t) => inline(t, null).replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>").replace(/`([^`]+)`/g, "<code>$1</code>");
  // `lead` is the bold opening, which is the whole news in a line; the docs' front page shows only that.
  return items.map((t) => ({ html: md1(t), text: t.replace(/\*\*|`/g, ""), lead: /^\*\*([^*]+)\*\*/.exec(t)?.[1]?.replace(/[.,:;]$/, "") }));
}

function readReleases() {
  return JSON.parse(fs.readFileSync(RELEASES, "utf8"))
    .filter((r) => vcmp(r.version, FIRST_RELEASE) >= 0)
    .sort((a, b) => vcmp(b.version, a.version))
    .map((r) => ({ version: r.version, date: day(r.pub_date), id: "v" + r.version.replace(/\./g, "-"), items: notes(r.notes) }));
}

