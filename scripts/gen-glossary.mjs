/* Write the glossary into ai-explained/ as static HTML.
 *
 * THE BUG THIS FIXES. The glossary page's four content elements were empty: #glossaryEntries,
 * #startHereList, #bigPictureList and #azJumpNav, all filled by js/glossary.js from
 * assets/ai-glossary-final.md on load. The page shipped the words "Entries shown: 0" and named
 * none of its 120 terms. To a crawler, an answer engine or a link preview, a 34KB plain-language
 * glossary was a heading and an empty search box.
 *
 * It is the third time this site has had this exact bug: the marketplace grid had it until
 * 2026-09-07 and the blog hub until the same day. It is the worst of the three, because
 * llms.txt lists this page by name, so the one page we point machines at was the one that
 * handed them nothing.
 *
 * WHAT THIS DOES NOT CHANGE. js/glossary.js still fetches the markdown and still redraws all
 * four regions on load, because the accordion, the search box and the jump links all need the
 * entries in hand. What ships in the markup is the unfiltered list in file order, which is
 * exactly what the script draws before anybody types anything.
 *
 * The renderer lives in js/glossary-card.js and both callers import it, for the reason set out
 * in that file and in js/blog-card.js: one builder, not two that drift.
 *
 * Usage:
 *   node scripts/gen-glossary.mjs           write the glossary into the page
 *   node scripts/gen-glossary.mjs --check   exit 1 if the page is out of date
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  parseGlossaryMarkdown,
  dedupeEntries,
  makeEntries,
  makeStartHere,
  makeBigPicture,
  makeJumpNav,
} from "../js/glossary-card.js";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const PAGE = path.join(ROOT, "ai-explained", "index.html");
const DATA = path.join(ROOT, "assets", "ai-glossary-final.md");

const BANNER =
  "<!-- GENERATED by scripts/gen-glossary.mjs from assets/ai-glossary-final.md. Do not hand-edit. " +
  "js/glossary.js redraws this on load; this copy is what everything that does not run scripts reads. -->";

/* Four regions, each its own element in the page, each replaced between its own opening and
 * closing tag. The count is a fifth and is handled separately: it is a number in a span, not
 * a region of markup, and it shipped as 0 on a page with 120 entries. */
const REGIONS = [
  { open: '<div id="azJumpNav" class="az-jump-nav" aria-label="Jump to letter">', close: "</div>", render: makeJumpNav },
  { open: '<div id="startHereList" class="start-here-list">', close: "</div>", render: makeStartHere },
  { open: '<div id="bigPictureList" class="big-picture-list">', close: "</div>", render: makeBigPicture },
  { open: '<div id="glossaryEntries" class="glossary-entries fade-up delay-2" role="list">', close: "</div>", render: makeEntries },
];

const COUNT_RE = /(<span id="glossaryCount">)(\d+)(<\/span>)/;

/* A region holds elements of the same tag name as its own closing tag, so the first </div>
 * after the opening one is not the matching one. Count depth on that tag name. Same helper,
 * same reason, as scripts/gen-blog.mjs. */
function regionBounds(html, region) {
  const start = html.indexOf(region.open);
  if (start === -1) throw new Error("not found in ai-explained/index.html: " + region.open);
  const tag = region.close.slice(2, -1);
  const re = new RegExp("<" + tag + "\\b[^>]*>|</" + tag + ">", "g");
  re.lastIndex = start;
  let depth = 0;
  let m;
  while ((m = re.exec(html))) {
    depth += m[0] === region.close ? -1 : 1;
    if (depth === 0) return { start, end: m.index + m[0].length };
  }
  throw new Error("never closed in ai-explained/index.html: " + region.open);
}

function main() {
  const check = process.argv.includes("--check");
  const entries = dedupeEntries(parseGlossaryMarkdown(fs.readFileSync(DATA, "utf8")));
  if (!entries.length) {
    console.log("gen-glossary: parsed no entries from assets/ai-glossary-final.md. Has the shape changed?");
    return 1;
  }

  let html = fs.readFileSync(PAGE, "utf8");
  let changed = false;

  /* Last region first, so replacing one cannot move an earlier one's offsets. */
  const inPageOrder = [...REGIONS].sort((a, b) => html.indexOf(a.open) - html.indexOf(b.open));
  for (const region of inPageOrder.reverse()) {
    const { start, end } = regionBounds(html, region);
    const wanted = region.open + BANNER + region.render(entries) + region.close;
    if (html.slice(start, end) !== wanted) {
      changed = true;
      html = html.slice(0, start) + wanted + html.slice(end);
    }
  }

  if (!COUNT_RE.test(html)) throw new Error('not found in ai-explained/index.html: <span id="glossaryCount">');
  const withCount = html.replace(COUNT_RE, (_, a, n, c) => a + entries.length + c);
  if (withCount !== html) changed = true;
  html = withCount;

  if (!changed) {
    console.log(`gen-glossary: clean. ${entries.length} entries in the page.`);
    return 0;
  }
  if (check) {
    console.log(
      "gen-glossary: ai-explained/index.html is out of date against assets/ai-glossary-final.md " +
      `(${entries.length} entries).\n\nRun: node scripts/gen-glossary.mjs`
    );
    return 1;
  }
  fs.writeFileSync(PAGE, html, "utf8");
  console.log(`gen-glossary: wrote ${entries.length} entries into ai-explained/.`);
  return 0;
}

process.exit(main());
