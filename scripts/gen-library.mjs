function main() {
  const check = process.argv.includes("--check");
  const preview = process.argv.includes("--preview");
  const { levels, sections } = JSON.parse(fs.readFileSync(DATA, "utf8"));
  const C = chrome();
  const all = preview ? sections : sections.filter((s) => s.youtube && !s.hold);
  const wanted = new Map(all.map((s) => [s.slug, page(s, all, levels, C, preview)]));

  /* The first player changes two things the site says about itself, on the same day (TRUST.md, the
     video library): the website entry gains the sentence about YouTube counting a play, and the
     privacy policy names YouTube among the outside resources. Publishing refuses until both do. */
  if (!preview && wanted.size) {
    const trust = fs.readFileSync(path.join(ROOT, "TRUST.md"), "utf8");
    const privacy = fs.readFileSync(path.join(ROOT, "privacy-policy", "index.html"), "utf8");
    const missing = [];
    if (!trust.includes("Pressing play on a video in the library loads YouTube")) missing.push("TRUST.md's website entry lacks the YouTube sentence");
    if (!/YouTube/.test(privacy)) missing.push("the privacy policy does not name YouTube");
    if (missing.length) {
      console.log("gen-library: not publishing, because " + missing.join(" and ") + ".");
      process.exit(1);
    }
  }

  const ours = fs.existsSync(OUT)
    ? fs.readdirSync(OUT, { withFileTypes: true })
        .filter((d) => d.isDirectory() && fs.existsSync(path.join(OUT, d.name, "index.html")) &&
          fs.readFileSync(path.join(OUT, d.name, "index.html"), "utf8").includes(BANNER))
        .map((d) => d.name)
    : [];
  const stale = ours.filter((slug) => !wanted.has(slug));
  const noCsp = (t) => t.replace(CSP_RE, "");
  let bad = 0;
  for (const [slug, html] of wanted) {
    const file = path.join(OUT, slug, "index.html");
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (have !== null && noCsp(have) === noCsp(html)) continue;
    if (check) { console.log("  out of date: learn/" + slug + "/"); bad++; continue; }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    // Keep the CSP gen-csp.py wrote, so a regeneration does not undo it.
    const csp = have && have.match(CSP_RE);
    fs.writeFileSync(file, csp ? html.replace(CSP_RE, csp[0]) : html);
    console.log("  wrote learn/" + slug + "/");
  }
  for (const slug of stale) {
    if (check) { console.log("  not published, still on disk: learn/" + slug + "/"); bad++; continue; }
    fs.rmSync(path.join(OUT, slug), { recursive: true });
    console.log("  removed learn/" + slug + "/");
  }
  const held = sections.filter((s) => s.hold).map((s) => `${s.n} (${s.hold})`);
  const waiting = sections.filter((s) => !s.youtube && !s.hold).length;
  if (check && bad) { console.log(`gen-library: ${bad} page(s) out of date. Run: node scripts/gen-library.mjs`); process.exit(1); }
  console.log(`gen-library: ${wanted.size} published, ${waiting} waiting for a YouTube id, ${held.length} held.`);
  for (const h of held) console.log("  held: " + h);
}

main();
