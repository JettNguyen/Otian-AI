# The answers under a draft are the app's own labels, emoji and all, from the Archie repo's
# texts/replies/card.rs. They were line icons until 2026-09-18, which is not how the app draws
# them (Jett: the mockup should have emojis like it usually would). Each one takes its color
# from its words, the way the app reads them (toneOf in src/words.ts): a yes is green, a change
# is gold, the way out is gray, anything else the accent. Send later is a yes for a later time and
# wears the accent, since September 28, 2026, when green read as a second Send beside the first.
ACTIONS = ["\u2705 Send", "\u270f\ufe0f Edit it", "\u23f0 Send later", "\u2715 Dismiss"]

AFFIRM = re.compile(r"^(yes|confirm|approve|ok|okay|do it|go ahead|send|apply|keep it|looks good|sounds good)\b")
DECLINE = re.compile(r"^(no|not now|cancel|dismiss|stop|discard|drop it|never ?mind|don'?t|don\u2019t|skip)\b")
AMEND = re.compile(r"^(change|edit|adjust|something else|not quite|reschedule)\b")
LATER = re.compile(r"^(send|reply|post|do it) later\b")


def action_parts(label):
    """A label split the way labelParts splits it: the mark in front, and the words."""
    m = re.match(r"^([^\w]+)", label)
    return (m.group(1).strip(), label[m.end():].strip()) if m else ("", label)


def tone_of(label):
    if label.startswith("\u2705"):
        return "go"
    if label.startswith("\u270f"):
        return "amend"
    if label.startswith(("\u2715", "\u2717")):
        return "stop"
    if label.startswith(("\u270d", "\u23f0")):
        return "plain"
    words = action_parts(label)[1].lower()
    if LATER.match(words):
        return "plain"
    return ("go" if AFFIRM.match(words) else "stop" if DECLINE.match(words)
            else "amend" if AMEND.match(words) else "plain")


def action_columns(labels):
    """How many answers go across (actionColumns): the longest label decides, a mark counting
    about three characters, and the rows are evened out. Four answers, the longest Send later,
    make two rows of two."""
    longest = max((3 if action_parts(l)[0] else 0) + len(action_parts(l)[1]) for l in labels)
    most = 4 if longest <= 6 else 3 if longest <= 9 else 2 if longest <= 15 else 1
    across = min(len(labels), most)
    rows = -(-len(labels) // across)
    return -(-len(labels) // rows)


