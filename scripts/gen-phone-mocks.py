_SF_WEIGHT = {"400": 1.0, "500": 1.0245, "600": 1.049, "650": 1.061, "700": 1.0735}


def sf_scale(size, weight):
    return (1.0 + (17.0 - float(size)) * 0.0117) * _SF_WEIGHT.get(weight, 1.0)


def tw(s, size, serif=False, weight="400"):
    """How wide that string is, drawn. Deliberately a little generous, because every caller
    uses this to decide how much room to leave, and erring narrow is the one direction that
    shows."""
    if serif:
        table, digit, scale = (_GEORGIA_BOLD if weight in ("600", "700") else _GEORGIA), 560, 1.0
    else:
        table, digit, scale = _SF, 600, sf_scale(size, weight)
    units = 0
    for ch in s:
        # An emoji draws from the system's color font at about an em and a quarter, and the
        # variation selector and joiner beside one draw nothing at all. The one exception is
        # the multiplication cross on Dismiss, which is a text glyph and three quarters of an em.
        if ch in ("\ufe0f", "\u200d"):
            continue
        if ch == "\u2715":
            units += 762
            continue
        if ord(ch) >= 0x2300:
            units += 1235
            continue
        units += table.get(ch, digit if ch.isdigit() else 560)
    return units * float(size) / 1000.0 * scale * 1.01


def wrap(s, width, size, serif=False, weight="400"):
    """The lines a paragraph breaks into at `width`, greedily, the way the phone breaks them."""
    lines, cur = [], ""
    for word in s.split(" "):
        trial = word if not cur else cur + " " + word
        if cur and tw(trial, size, serif, weight) > width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def clamp(lines, most, width, size, serif=False, weight="400"):
    """numberOfLines: at most `most` lines, the last one cut with an ellipsis when there was
    more, which is how the app shortens a line it has no room for."""
    if len(lines) <= most:
        return lines
    last = lines[most - 1] + " " + lines[most]
    while last and tw(last + "\u2026", size, serif, weight) > width:
        last = last[:-1]
    return lines[:most - 1] + [last.rstrip(" ,.") + "\u2026"]


def baseline(top, lh, size, serif=False):
    """Where a line's baseline sits when its line box starts at `top`, the way a browser centers
    a face's ascent and descent in the line height. SF Pro's are 0.95 and 0.24 of the size,
    Georgia's 0.917 and 0.219."""
    asc, desc = (0.917, 0.219) if serif else (0.952, 0.241)
    return top + (lh - (asc + desc) * size) / 2.0 + asc * size


