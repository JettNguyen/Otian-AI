def rect(x, y, w, h, r=0, fill="none", stroke=None, sw=1, extra=""):
    s = '<rect x="%s" y="%s" width="%s" height="%s"' % (f(x), f(y), f(w), f(h))
    if r:
        s += ' rx="%s"' % f(r)
    s += ' fill="%s"' % fill
    if stroke:
        s += ' stroke="%s" stroke-width="%s"' % (stroke, f(sw))
    return s + extra + "/>"


def text(x, y, t, size=17, fill="var(--text)", weight="400", anchor="start", serif=False, extra=""):
    s = '<text x="%s" y="%s" font-size="%s" fill="%s" font-weight="%s" text-anchor="%s"' % (
        f(x), f(y), f(size), fill, weight, anchor)
    if serif:
        s += ' font-family="%s"' % SERIF
    return s + extra + ">%s</text>" % esc(t)


def circle(cx, cy, r, fill="none", stroke=None, sw=1, extra=""):
    s = '<circle cx="%s" cy="%s" r="%s" fill="%s"' % (f(cx), f(cy), f(r), fill)
    if stroke:
        s += ' stroke="%s" stroke-width="%s"' % (stroke, f(sw))
    return s + extra + "/>"


