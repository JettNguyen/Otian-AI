def device(inner, ox, oy):
    """The phone around a screen. Until 2026-09-18 this was one dark rounded rectangle, which
    read as a card with a screen on it (Jett: "too bland"). What a phone has that a card does
    not: a body that is lit from one corner and darker toward the other, a bright line where
    the glass meets the metal, a black bezel between the two, the buttons on its sides, and the
    island at the top of the screen with the lens in it. None of it is Archie; it is what makes
    the rest read as a phone. The screen's corner is the kit's 54, and the island and its lens
    stand where the kit and the stage's device put them, 14 down and 96 by 30, so the status
    bar's row is on the island's middle in both renderings."""
    cid, gid = uid("sc"), uid("gs")
    P = SHELL_PAD
    return ('<g transform="translate(%s,%s)">' % (f(ox), f(oy))
            + '<defs><clipPath id="%s">%s</clipPath>' % (cid, rect(0, 0, W, H, SCREEN_R, "#000"))
            + '<linearGradient id="%s" x1="0" y1="0" x2="0.4" y2="1">' % gid
            + '<stop offset="0" style="stop-color:var(--shell-hi)"/>'
            + '<stop offset="0.45" style="stop-color:var(--shell)"/>'
            + '<stop offset="1" style="stop-color:var(--shell-lo)"/></linearGradient></defs>'
            # the buttons, on the metal behind the body: volume on the left, power on the right
            + rect(-P - 3, 118, 3.5, 34, 1.5, "var(--shell-lo)")
            + rect(-P - 3, 166, 3.5, 54, 1.5, "var(--shell-lo)")
            + rect(-P - 3, 232, 3.5, 54, 1.5, "var(--shell-lo)")
            + rect(W + P - 0.5, 186, 3.5, 84, 1.5, "var(--shell-lo)")
            # the body, its lit edge, and the bezel, each concentric with the screen's corner
            + rect(-P, -P, W + P * 2, H + P * 2, SCREEN_R + P, "url(#%s)" % gid)
            + rect(-P + 0.75, -P + 0.75, W + P * 2 - 1.5, H + P * 2 - 1.5, SCREEN_R + P - 0.75,
                   "none", "var(--edge)", 1)
            + rect(-4, -4, W + 8, H + 8, SCREEN_R + 4, "#0B0B0A")
            # the screen
            + '<g clip-path="url(#%s)">' % cid
            + rect(0, 0, W, H, 0, "var(--bg)") + '<g class="mk-ui">' + inner + "</g></g>"
            # the island and the lens, over the status bar's clear middle
            + rect(W / 2 - 48, 14, 96, 30, 15, "#000")
            + circle(W / 2 + 27, 29, 7, "#121820")
            + circle(W / 2 + 25.2, 27.2, 1.8, "rgba(130,170,225,.35)")
            + "</g>")


def phone(body, ox, oy):
    return device(body, ox, oy)


def build():
    """The two renderings: the stage phone, then the stills."""
    _n[0] = 0
    caption_y = 856.0

    # The stage: the shell once, the three screens inside it, screen i on act i. aria-hidden,
    # because the scene it stands in carries the accessible name for the whole drawing, the
    # way the homepage's does; the stills below are what a machine reads.
    new_doc()
    bodies = []
    for i, (fn, cap, desc) in enumerate(SCREENS):
        _beat["act"] = i
        bodies.append(fn())
    _beat["act"] = None
    # The screen alone, at the screen's own size: the device around it on the stage is the
    # homepage phone's, in HTML (styles.css section 49, the .dp-* classes), which is what gives
    # it a rim, a chamfer and light that moves with its angle. The stylesheet lights one
    # .mk-scr at a time and the rest are not painted.
    stage = ('<svg class="mk mk-stage" viewBox="0 0 %s %s" aria-hidden="true" focusable="false"'
             ' xmlns="http://www.w3.org/2000/svg" style="font-family:inherit">' % (f(W), f(H)) + THEME
             + doc_defs() + rect(0, 0, W, H, 0, "var(--bg)") + '<g class="mk-ui">'
             + "".join('<g class="mk-scr%s" data-scr="%d">%s</g>'
                       % (" is-on" if i == 0 else "", i, body) for i, body in enumerate(bodies))
             + "</g></svg>")

    # The stills: one drawing per screen, each named, in a row the stylesheet stacks narrow.
    # The caption under each phone is the site's, so it stays in the page's face; only the
    # screen is set in the phone's.
    items = []
    for i, (fn, cap, desc) in enumerate(SCREENS):
        tid = "mks%d" % (i + 1)
        new_doc()
        drawn = phone(fn(), 11.0, 11.0)
        svg = ('<svg class="mk" viewBox="0 0 412 874" role="img" aria-labelledby="%s"'
               ' xmlns="http://www.w3.org/2000/svg" style="font-family:inherit;overflow:visible">' % tid
               + THEME + '<title id="%s">%s</title>' % (tid, esc(desc)) + doc_defs() + drawn
               + text(206, caption_y, cap, 21, "currentColor", "500", "middle") + "</svg>")
        items.append('<div class="mb-still-item">%s</div>' % svg)
    stills = ('<div class="mb-still" aria-label="Three screens from Archie Mobile">'
              + "".join(items) + "</div>")

    return stage, stills


def main():
    check = "--check" in sys.argv
    html = open(PAGE, encoding="utf-8").read()
    stage, stills = build()
    new = html
    for begin, end, body in ((STAGE_BEGIN, STAGE_END, stage), (BEGIN, END, stills)):
        pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
        if not pat.search(new):
            print("gen-phone-mocks: cannot find %r in the page" % begin)
            return 1
        block = begin + "\n              " + body + "\n              " + end
        new = pat.sub(lambda _: block, new, count=1)

    if new == html:
        print("gen-phone-mocks: clean. 3 screens, 2 renderings.")
        return 0
    if check:
        print("gen-phone-mocks: archie/mobile/ is out of date. Run scripts/gen-phone-mocks.py")
        return 1
    open(PAGE, "w", encoding="utf-8").write(new)
    print("gen-phone-mocks: wrote 3 screens as the stage phone and the three stills.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
