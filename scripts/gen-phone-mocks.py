def status_bar(clock="7:00"):
    """The phone's own bar. Nothing here is Archie: it is what makes the rest read as a phone.

    Everything sits on one midline with matching margins left and right, laid out from the
    right edge in: battery, wifi, signal. A silenced-bell glyph used to sit beside the clock
    because the drawings are quiet ones; it read as a thing that had happened to the phone,
    which is a fact about nothing, so it is gone.

    The clock reads 7:00, which is the homepage's morning brief and the site's own hour. It read
    9:41 until 2026-09-17: the time Apple stops every clock in its own marketing, and the plainest
    way a drawing of a generic phone tells a reader it is meant to be an iPhone. The drawing is
    ours and so is the hour on it.
    """
    mid = 30.0
    o = [text(30, mid + 5.4, clock, 15, "var(--ink)", "600")]

    # battery, its right edge 30 in from the screen edge, to match the clock's 30. Full, and so
    # are the bars below, because a drawing is not a phone that happens to be at 65% (Jett,
    # 2026-09-18); the homepage's phone and the kit it is ported from say the same.
    o.append(rect(332, mid - 6.2, 26, 12.4, 4.2, "none", "var(--ink)", 1.2, ' opacity=".4"'))
    o.append(rect(358.9, mid - 2.4, 1.8, 4.8, 0.9, "var(--ink)", extra=' opacity=".28"'))
    o.append(rect(334.4, mid - 4.2, 21.2, 8.4, 2.2, "var(--ink)"))

    # wifi, two arcs over a dot
    o.append('<g transform="translate(308,%s)" fill="none" stroke="var(--ink)" stroke-width="1.9"'
             ' stroke-linecap="round"><path d="M0.4,5.4 Q8,-1.6 15.6,5.4"/>'
             '<path d="M3.6,8.8 Q8,4.5 12.4,8.8"/></g>' % f(mid - 8))
    o.append(circle(316, mid + 4.4, 1.7, "var(--ink)"))

    # signal, four bars standing on the same baseline as the clock, all of them lit
    for i in range(4):
        h = 4.4 + i * 2.4
        o.append(rect(279 + i * 5.8, mid + 5.6 - h, 3.6, h, 1.3, "var(--ink)"))
    return "".join(o)


