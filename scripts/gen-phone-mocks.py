CHAT_AT = [None, 0.1, 0.4]

BUB_W = 0.86 * (W - 2 * MARGIN)   # both sides get the same column, 86% of the transcript
BUB_PADX, BUB_PADY = 16.0, 12.0   # inside a bubble
BUB_FS, BUB_LH = 17.0, 24.0       # a message is set at 17 on 24, the size Messages sets one in
BUB_R, BUB_TAIL = 20.0, 6.0       # 20 round, and 6 at the tail that says who is speaking
BUB_GAP = 12.0                    # between one message and the next
QUOTE_IN = 15.0                   # a quote's 3 point rule and the 12 after it
ACT_H = 48.0                      # one answer in the bar
TRANSCRIPT_PAD = 24.0             # under the last message, above the message box


def bubble_path(x, y, w, h, mine):
    """A message's shape: every corner 20 round except the bottom one on the speaker's side."""
    r, t = BUB_R, BUB_TAIL
    bl, br = (r, t) if mine else (t, r)
    return ('<path d="M%s %sH%sA%s %s 0 0 1 %s %sV%sA%s %s 0 0 1 %s %sH%sA%s %s 0 0 1 %s %sV%sA%s %s 0 0 1 %s %sZ"'
            ' fill="%s"/>') % (
        f(x + r), f(y), f(x + w - r), f(r), f(r), f(x + w), f(y + r),
        f(y + h - br), f(br), f(br), f(x + w - br), f(y + h),
        f(x + bl), f(bl), f(bl), f(x), f(y + h - bl),
        f(y + r), f(r), f(r), f(x + r), f(y),
        "var(--accent-sub)" if mine else "var(--card)")


def answer_bar(x, y, w, labels):
    """The answers to a card (InlineActions) as a rounded bar inside the message, like an
    alert's buttons: 10 in from the message's sides and bottom, 14 round, a soft outline and soft
    rules between the cells, and each cell washed in the hue of what it answers."""
    cols = action_columns(labels)
    rows = [labels[i:i + cols] for i in range(0, len(labels), cols)]
    h = ACT_H * len(rows) + len(rows) + 1
    cid = uid("ab")
    o = ['<defs><clipPath id="%s">%s</clipPath></defs>' % (cid, rect(x, y, w, h, 14)),
         rect(x, y, w, h, 14, "var(--rule)"), '<g clip-path="url(#%s)">' % cid]
    for r, row in enumerate(rows):
        cw = (w - len(row) - 1) / len(row)
        cy = y + 1 + r * (ACT_H + 1)
        for c, label in enumerate(row):
            cx = x + 1 + c * (cw + 1)
            tone = tone_of(label)
            wash = {"go": "var(--opt-go)", "amend": "var(--opt-amend)", "stop": "var(--opt)",
                    "plain": "var(--opt-plain)"}[tone]
            ink = {"go": "var(--green)", "amend": "var(--gold)", "stop": "var(--text2)",
                   "plain": "var(--accent-strong)"}[tone]
            weight = "600" if tone == "go" else "500"
            mark, words = action_parts(label)
            mw = tw(mark, 17) if mark else 0
            lw = tw(words, 17, weight=weight)
            sx = cx + (cw - (mw + (6 if mark else 0) + lw)) / 2
            by = baseline(cy + (ACT_H - 22) / 2, 22, 17)
            o.append(rect(cx, cy, cw, ACT_H, 0, wash))
            if mark:
                o.append(text(sx, by, mark, 17, ink, "400"))
            o.append(text(sx + mw + (6 if mark else 0), by, words, 17, ink, weight))
    return "".join(o) + "</g>", h


def chat_item(m, measure_only=False, y=0.0):
    """One message laid out: its drawing and how tall it stands, the time under it included
    when it says one."""
    inner = BUB_W - 2 * BUB_PADX
    if "quote" in m:
        lead = wrap(m["lead"], inner, BUB_FS)
        quote = wrap(m["quote"], inner - QUOTE_IN, BUB_FS)
        body_h = BUB_LH * len(lead) + 8 + 4 + BUB_LH * len(quote)
        rows = -(-len(m["actions"]) // action_columns(m["actions"]))
        acts_h = ACT_H * rows + rows + 1
        w, h = BUB_W, BUB_PADY + body_h + 12 + acts_h + 10
        lines = None
    else:
        lines = wrap(m["text"], inner, BUB_FS)
        # A bubble that fits on one line hugs it; one that wraps takes the whole column, which is
        # what fit-content does with a max-width of 86%.
        w = BUB_W if len(lines) > 1 else min(BUB_W, tw(lines[0], BUB_FS) + 2 * BUB_PADX)
        h = 2 * BUB_PADY + BUB_LH * len(lines)
    if measure_only:
        return None, h
    x = (W - MARGIN - w) if m["mine"] else MARGIN
    o = [bubble_path(x, y, w, h, m["mine"])]
    tx = x + BUB_PADX
    if lines is not None:
        for i, ln in enumerate(lines):
            o.append(text(tx, baseline(y + BUB_PADY + BUB_LH * i, BUB_LH, BUB_FS), ln, BUB_FS))
    else:
        ty = y + BUB_PADY
        for i, ln in enumerate(lead):
            o.append(text(tx, baseline(ty + BUB_LH * i, BUB_LH, BUB_FS), ln, BUB_FS))
        # the quoted draft (.md .quote): the accent's 3 point rule, 12 in, 2 above and below
        qy = ty + BUB_LH * len(lead) + 8
        o.append(rect(tx, qy, 3, 4 + BUB_LH * len(quote), 0, "var(--accent)"))
        for i, ln in enumerate(quote):
            o.append(text(tx + QUOTE_IN, baseline(qy + 2 + BUB_LH * i, BUB_LH, BUB_FS), ln, BUB_FS))
        bar, _ = answer_bar(x + 10, qy + 4 + BUB_LH * len(quote) + 12, w - 20, m["actions"])
        o.append(bar)
    assert x >= MARGIN - 0.01 and x + w <= W - MARGIN + 0.01, "a bubble runs past the page's margin"
    return "".join(o), h


