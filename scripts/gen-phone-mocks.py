# Two token sets, because these are drawings of an app that has both and the page is read in
# both: the kit's iosLight and iosDark (src/theme.ts in the app), under the kit's own names so a
# value can be searched for in both files. The answer bar's washes are mixed here the way the kit
# mixes them with color-mix, so each is written down once as the two colors it is made of.
def mix(a, b, t):
    """`t` of color a and the rest of color b, as color-mix(in srgb, a t, b) makes it."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join("%02X" % round(x * t + y * (1 - t)) for x, y in zip(pa, pb))


def tokens(p, shell):
    t = dict(p)
    t["opt"] = mix(p["card"], p["text"], 0.95)              # the way out's gray
    t["opt-go"] = mix(p["card"], p["green-hue"], 0.86)      # a yes
    t["opt-amend"] = mix(p["card"], p["gold-hue"], 0.86)    # a change
    t["opt-plain"] = mix(p["card"], p["accent"], 0.86)      # anything else
    t["rule"] = mix(p["card"], p["text"], 0.78)             # between the answers
    del t["green-hue"], t["gold-hue"]
    t.update(shell)
    return ";".join("--%s:%s" % kv for kv in t.items())


