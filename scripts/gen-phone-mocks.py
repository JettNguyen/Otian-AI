def build():
    _n[0] = 0
    caption_y = 856.0

    # desktop: the trio, side by side
    parts = []
    titles = []
    for i, (fn, cap, desc) in enumerate(SCREENS):
        ox = 41.0 + i * 460.0
        parts.append(phone(fn(), ox, 11.0))
        parts.append(text(ox + W / 2, caption_y, cap, 21, "currentColor", "500", "middle"))
        titles.append(desc)
    desk = ('<svg class="mk explain-svg--desktop" viewBox="0 0 1392 884" role="img"'
            ' aria-labelledby="mockt-desktop" xmlns="http://www.w3.org/2000/svg"'
            ' style="max-width:960px;font-family:inherit">' + THEME
            + '<title id="mockt-desktop">Three screens from Archie Mobile. %s</title>'
            % esc(" ".join(titles)) + "".join(parts) + "</svg>")

    # mobile: one per gallery item
    items = []
    for i, (fn, cap, desc) in enumerate(SCREENS):
        tid = "mkg%d" % (i + 1)
        svg = ('<svg class="mk" viewBox="0 0 412 874" role="img" aria-labelledby="%s"'
               ' xmlns="http://www.w3.org/2000/svg" style="font-family:inherit">' % tid
               + THEME + '<title id="%s">%s</title>' % (tid, esc(desc))
               + phone(fn(), 11.0, 11.0)
               + text(206, caption_y, cap, 21, "currentColor", "500", "middle") + "</svg>")
        items.append('<div class="screenshot-gallery-item">%s</div>' % svg)

    gallery = ('<div class="screenshot-gallery mk-gallery" data-pps="30"'
               ' aria-label="Three screens from Archie Mobile">'
               '<div class="screenshot-gallery-track">' + "".join(items) + "</div></div>")

    return "            " + desk + "\n            " + gallery


def main():
    check = "--check" in sys.argv
    html = open(PAGE, encoding="utf-8").read()
    block = BEGIN + "\n" + build() + "\n            " + END
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pat.search(html):
        new = pat.sub(lambda _: block, html, count=1)
    else:
        # first run: swallow the hand-written figure contents
        old = re.compile(r'(<figure class="explain-figure fade-up delay-2">\s*).*?(\s*</figure>)', re.S)
        if not old.search(html):
            print("gen-phone-mocks: cannot find the figure to replace")
            return 1
        new = old.sub(lambda m: m.group(1) + block + m.group(2), html, count=1)

    if new == html:
        print("gen-phone-mocks: clean. 3 screens, 2 renderings.")
        return 0
    if check:
        print("gen-phone-mocks: archie/mobile/ is out of date. Run scripts/gen-phone-mocks.py")
        return 1
    open(PAGE, "w", encoding="utf-8").write(new)
    print("gen-phone-mocks: wrote 3 screens as the desktop trio and the mobile gallery.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
