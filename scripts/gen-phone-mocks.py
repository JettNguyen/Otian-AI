def rect(x, y, w, h, r=0, fill="none", stroke=None, sw=1, extra=""):
    s = '<rect x="%s" y="%s" width="%s" height="%s"' % (f(x), f(y), f(w), f(h))
    if r:
        s += ' rx="%s"' % f(r)
    s += ' fill="%s"' % fill
    if stroke:
        s += ' stroke="%s" stroke-width="%s"' % (stroke, f(sw))
    return s + extra + "/>"


def text(x, y, t, size=13.5, fill="var(--ink)", weight="400", anchor="start", serif=False):
    s = '<text x="%s" y="%s" font-size="%s" fill="%s" font-weight="%s" text-anchor="%s"' % (
        f(x), f(y), f(size), fill, weight, anchor)
    if serif:
        s += ' font-family="%s"' % SERIF
    return s + ">%s</text>" % esc(t)


def circle(cx, cy, r, fill="none", stroke=None, sw=1):
    s = '<circle cx="%s" cy="%s" r="%s" fill="%s"' % (f(cx), f(cy), f(r), fill)
    if stroke:
        s += ' stroke="%s" stroke-width="%s"' % (stroke, f(sw))
    return s + "/>"


def line(x1, y1, x2, y2, stroke="var(--bd)", sw=1):
    return '<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="%s"/>' % (
        f(x1), f(y1), f(x2), f(y2), stroke, f(sw))


def icon(paths, x, y, scale=1.0, stroke="var(--ink3)", fill="none", sw=1.8):
    """A 24x24 stroked glyph, the same vocabulary the app's tab bar and rows use."""
    return ('<g transform="translate(%s,%s) scale(%s)" fill="%s" stroke="%s" stroke-width="%s"'
            ' stroke-linecap="round" stroke-linejoin="round">%s</g>') % (
        f(x), f(y), "%.4f" % scale, fill, stroke, f(sw), paths)


