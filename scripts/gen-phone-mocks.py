# The shared pieces one drawing asks for (a symbol's mask, the glass's shadow, the fade under a
# bar) are made once per <svg> and written into its <defs>. new_doc() starts a drawing and
# doc_defs() hands back what it asked for.
_doc = {"defs": {}}


def new_doc():
    _doc["defs"] = {}


def doc_def(key, build):
    if key not in _doc["defs"]:
        i = uid(key.replace("-", ""))
        _doc["defs"][key] = (i, build(i))
    return _doc["defs"][key][0]


def doc_defs():
    return "<defs>%s</defs>" % "".join(m for _, m in _doc["defs"].values())


def esc(t):
    return (t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace("’", "&rsquo;").replace("·", "&middot;"))


def f(v):
    """Trim floats so the markup does not carry 14 decimals of nothing."""
    s = "%.1f" % float(v)
    return s[:-2] if s.endswith(".0") else s


