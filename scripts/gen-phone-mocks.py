#!/usr/bin/env python3
"""gen-phone-mocks.py: the three Archie Mobile screens on archie/mobile/, drawn once.

The page shows three phone screens twice: as a trio side by side on a wide window, and as
the scrolling gallery under 640px. That is six drawings of three screens, and until
2026-09-14 all six were hand-written SVG pasted into the page. A styling change meant six
edits, which is how the two halves drift: a card radius fixed in the gallery and missed in
the trio reads as a bug nobody can find.

So the screens live here, as content plus components, and this writes both renderings into
the page between markers. Same arrangement as gen-marketplace.mjs and gen-blog.mjs: the
result is committed, and --check is what stops the committed markup drifting from its source.

WHAT IT IS AND IS NOT. These are drawings of the app, not screenshots of it, and the
distinction is load-bearing: the app is in testing and its screens still move. What the
drawings owe the reader is that every element on them is one the app actually has, doing
what the app actually does. The styling was brought to the shipping app's on 2026-09-14
from screenshots of the real build: the status bar, the header with its wordmark and agent
picker, the stacked action card under a draft, the per-skill toggle and chevron, the tab
bars and their counts. The CONTENT is the site's own and stays that way, because the real
screens carry a real person's mail.

    python3 scripts/gen-phone-mocks.py           write the page
    python3 scripts/gen-phone-mocks.py --check   fail if the page is out of date
"""

