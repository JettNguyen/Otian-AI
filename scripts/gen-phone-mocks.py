def avatar(cx, cy, r, kind, dot=False):
    cid = uid("fc")
    o = ['<defs><clipPath id="%s"><circle cx="%s" cy="%s" r="%s"/></clipPath></defs>' % (
        cid, f(cx), f(cy), f(r))]
    o.append(circle(cx, cy, r, "var(--accS)"))
    o.append('<g clip-path="url(#%s)"><g transform="translate(%s,%s) scale(%s)">%s</g></g>' % (
        cid, f(cx - r), f(cy - r), "%.4f" % (r / 100.0), face_body(kind)))
    if dot:
        # the app puts a presence dot on the agent in the header, and it is the one place
        # "running" is stated without a word for it
        o.append(circle(cx + r * 0.72, cy + r * 0.72, r * 0.26, "var(--grn)", "var(--bg)", 1.5))
    return "".join(o)


